const getSavedLanguage = () => {
    const savedLanguage = window.localStorage.getItem("ponno-kini-language");
    return savedLanguage === "bn" ? "bn" : "en";
};

let activeLanguage = getSavedLanguage();

export function setActiveLanguage(language) {
    if (language !== "en" && language !== "bn") {
        throw new RangeError(`Unsupported language: ${language}`);
    }
    activeLanguage = language;
}

export function t(text, replacements = {}) {
    if (typeof text !== "string") return text;

    const translated =
        activeLanguage === "bn" ? translations.get(text) ?? text : text;
    return Object.entries(replacements).reduce(
        (result, [key, value]) =>
            result.replaceAll(`:${key}`, String(value)),
        translated,
    );
}

export function getIntlLocale() {
    return activeLanguage === "bn" ? "bn-BD" : "en-BD";
}
